internal data class HomePhrases(
    val portalChip: String,
    val honourLine: String,
    val title: String,
    val subtitle: String,
    val tagline: String,
    val getStarted: String,
    val signIn: String,
    val signInOfficial: String,
    val createAccount: String,
    val chooseLanguage: String,
    val searchLanguages: String,
)

internal fun HomePhrases.applyTo(copy: RathYatraCopy) {
    copy.portalChip = portalChip
    copy.honourLine = honourLine
    copy.title = title
    copy.subtitle = subtitle
    copy.tagline = tagline
    copy.getStarted = getStarted
    copy.signIn = signIn
    copy.signInTitle = signIn
    copy.signInOfficial = signInOfficial
    copy.alreadyRegistered = signInOfficial
    copy.createAccount = createAccount
    copy.platformTitle = title
    copy.platformBody = tagline
    copy.festivalTitle = subtitle
    copy.chooseLanguage = chooseLanguage
    copy.searchLanguages = searchLanguages
}

