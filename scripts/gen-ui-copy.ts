/**
 * Builds the Android language catalog from the website copy plus the
 * admin, check-in, and form strings that exist only in the app.
 *
 * Run from the repository root: npx tsx scripts/gen-ui-copy.ts
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { copyFor, type AppCopy } from '../web/src/lib/copy.ts'
import { LANGUAGE_CODES, type LangCode } from '../web/src/lib/languages.ts'
import { EXTRA, EXTRA_KEYS } from './ui-extra-copy.ts'

const ORDER = LANGUAGE_CODES

function kotlinString(value: string): string {
  return (
    '"' +
    value
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\$/g, '\\$')
      .replace(/\r/g, '')
      .replace(/\n/g, '\\n') +
    '"'
  )
}

function packName(code: string): string {
  return 'pack_' + code
}

const chunks: string[] = []
chunks.push(`@file:Suppress("LargeClass", "MaxLineLength", "ktlint")

package com.example.sahakarbharati.core.copy

/** Generated by scripts/gen-ui-copy.ts. Do not edit by hand. */
internal fun uiPack(language: AppLanguage): Map<String, String> = when (language) {`)

for (const code of ORDER) {
  chunks.push(`    AppLanguage.${code.toUpperCase()} -> ${packName(code)}()`)
}
chunks.push('}\n')

for (const code of ORDER) {
  const shared = copyFor(code as LangCode) as AppCopy
  const extra = EXTRA[code]
  if (!extra) throw new Error('Missing extra copy for ' + code)
  for (const key of EXTRA_KEYS) {
    if (!extra[key]) throw new Error(code + ' is missing ' + key)
  }
  const months = shared.monthNames.split(/\s+/).filter(Boolean)
  if (months.length !== 12) {
    throw new Error(code + ' monthNames has ' + months.length + ' words')
  }
  const body: string[] = []
  body.push(`private fun ${packName(code)}(): Map<String, String> = buildMap {`)
  for (const [key, value] of Object.entries(shared)) {
    body.push(`    put(${kotlinString(key)}, ${kotlinString(String(value))})`)
  }
  for (const key of EXTRA_KEYS) {
    body.push(`    put(${kotlinString(key)}, ${kotlinString(extra[key])})`)
  }
  body.push('}')
  chunks.push(body.join('\n'))
  chunks.push('')
}

const out = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../android/app/src/main/java/com/example/sahakarbharati/core/copy/UiCatalog.kt',
)
writeFileSync(out, chunks.join('\n'), 'utf8')
console.log('Wrote', out)
